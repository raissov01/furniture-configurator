import type { Room, Vec3, WallId } from '../src/core/index'
import { wallById } from '../src/core/index'

/**
 * Камераның НЫСАНАСЫ — бөлме ортасы, көз деңгейінде (биіктіктің жартысы).
 * Барлық төрт қабырға көрінісі БІР осы нүктеге қарайды, тек камераның
 * ӨЗІ әр қабырғада басқа жақта тұрады.
 */
export function wallElevationTarget(room: Room): Vec3 {
  return { x: room.width / 2, y: room.height / 2, z: room.depth / 2 }
}

/**
 * Камераның НЫСАНАДАН ЫҒЫСУЫ (world space, мм): `target + offset` —
 * камераның дәл орны. Қабырғаның шынайы `inward` векторымен есептеледі,
 * ешбір бұрылым (rotationY) айналымы жоқ — сондықтан таңбасы дәлелденеді.
 */
export function wallElevationOffset(room: Room, wallId: WallId, distance: number): Vec3 {
  const wall = wallById(room, wallId)
  return {
    x: wall.inward.x * distance,
    y: 0,
    z: wall.inward.z * distance,
  }
}
