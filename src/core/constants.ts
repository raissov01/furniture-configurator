/**
 * Константаларды қабаттап біріктіру: үнсіз келісім → жоба профилі → кабинет.
 * `undefined` мәні мұралауды ЖОЙМАЙДЫ — jsonда өріс жоқ болса, астыңғы
 * қабаттың мәні қалады.
 */
export function mergeSettings(...layers: (SettingsOverride | undefined)[]): ConstructionSettings {
  const result: ConstructionSettings = { ...DEFAULT_SETTINGS }
  for (const layer of layers) {
    if (!layer) continue
    for (const [key, value] of Object.entries(layer)) {
      if (value !== undefined) {
        // Enum/array мәндері де профиль қабатымен бірге көшеді.
        ;(result as unknown as Record<string, unknown>)[key] = value
      }
    }
  }
  return result
}
